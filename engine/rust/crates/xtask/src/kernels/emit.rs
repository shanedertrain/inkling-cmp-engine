//! Writes `ink-kernels/src/gen.rs`: the kernel table, `#[repr(C)]` struct mirrors with compile-time layout assertions,
//! and one typed launcher per kernel (a method of `ink_kernels::Kernels`).

use std::collections::BTreeMap;
use std::fmt::Write;

use anyhow::{Result, bail, ensure};

use super::ctype::CType;
use super::{Pack, StructDef};

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn",
    "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self",
    "static", "struct", "super", "trait", "true", "try", "type", "unsafe", "use", "where", "while", "abstract",
    "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield",
];

/// A Rust keyword (strict or reserved, edition 2024).
pub fn is_keyword(s: &str) -> bool {
    KEYWORDS.contains(&s)
}

/// A field name as a Rust identifier (`in` -> `r#in`).
fn ident(s: &str) -> String {
    if is_keyword(s) { format!("r#{s}") } else { s.to_string() }
}

/// `da_decode_attn_kernel_0_false` -> `DaDecodeAttnKernel0False`.
fn camel(key: &str) -> String {
    key.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// The generated file.
pub fn gen_rs(p: &Pack) -> Result<String> {
    let mut o = String::new();
    writeln!(
        o,
        "//! Generated by `xtask gen-kernels` from the kernel pack (`engine/kernels/pack/`): do not edit."
    )?;
    writeln!(
        o,
        "//! Regenerate after any change to the pack's inputs (the kpack id changes; ink-kernels' build.rs"
    )?;
    writeln!(o, "//! refuses a pack whose id differs from [`KPACK_ID`]).")?;
    writeln!(o, "#![allow(non_snake_case, clippy::too_many_arguments)]")?;
    writeln!(o)?;
    writeln!(
        o,
        "use ink_cuda::{{Bf16, DevPtr, KernelArgs, LaunchCfg, Result, Stream}};"
    )?;
    writeln!(o)?;
    writeln!(o, "use crate::{{CubinInfo, F16, KernelInfo, Kernels, Ptr, push_ptr}};")?;
    writeln!(o)?;
    writeln!(
        o,
        "/// Id of the kernel pack this file was generated from (`manifest.json` `kpack_id`)."
    )?;
    writeln!(o, "pub const KPACK_ID: &str = \"{}\";", p.kpack_id)?;
    writeln!(o)?;
    writeln!(
        o,
        "/// FNV-1a 64 of the generator's sources (`xtask/src/kernels/`), checked by `check_fresh.py`: a gen.rs written"
    )?;
    writeln!(
        o,
        "/// by another generator version is stale even when the pack is not."
    )?;
    writeln!(o, "pub const GENERATOR_FNV1A64: u64 = {:#018x};", p.generator)?;
    writeln!(o)?;
    writeln!(o, "/// The pack's cubins, in [`KernelInfo::tu`] order.")?;
    writeln!(o, "pub const CUBINS: [CubinInfo; {}] = [", p.cubins.len())?;
    for c in &p.cubins {
        writeln!(
            o,
            "    CubinInfo {{ tu: \"{}\", file: \"{}\", bytes: {}, sha256: \"{}\", fnv1a64: {:#018x} }},",
            c.tu, c.file, c.bytes, c.sha256, c.fnv1a64
        )?;
    }
    writeln!(o, "];")?;
    emit_table(&mut o, p)?;
    emit_structs(&mut o, &p.structs)?;
    emit_launchers(&mut o, p)?;
    Ok(o)
}

fn emit_table(o: &mut String, p: &Pack) -> Result<()> {
    let mut seen = BTreeMap::new();
    writeln!(o)?;
    writeln!(o, "/// Every kernel of the pack, by its keys.toml key.")?;
    writeln!(o, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")?;
    writeln!(o, "pub enum KernelId {{")?;
    for l in &p.launchers {
        let v = camel(&l.key);
        if let Some(other) = seen.insert(v.clone(), l.key.clone()) {
            bail!("keys {other} and {} give the same variant name {v}", l.key);
        }
        writeln!(o, "    /// `{}`", l.demangled)?;
        writeln!(o, "    {v},")?;
    }
    writeln!(o, "}}")?;
    writeln!(o)?;
    writeln!(o, "/// Kernel table, in [`KernelId`] order.")?;
    writeln!(o, "pub static KERNELS: [KernelInfo; {}] = [", p.launchers.len())?;
    for l in &p.launchers {
        writeln!(
            o,
            "    KernelInfo {{ key: \"{}\", tu: {}, symbol: \"{}\", params: &[{}], param_bytes: {}, coop: {} }},",
            l.key,
            l.tu,
            l.symbol,
            l.cpp_params
                .iter()
                .map(|p| format!("{p:?}"))
                .collect::<Vec<_>>()
                .join(", "),
            l.param_bytes,
            l.coop
        )?;
    }
    writeln!(o, "];")?;
    Ok(())
}

fn split_name(cpp: &str) -> (Option<&str>, &str) {
    match cpp.rsplit_once("::") {
        Some((ns, n)) => (Some(ns), n),
        None => (None, cpp),
    }
}

fn emit_structs(o: &mut String, structs: &[StructDef]) -> Result<()> {
    let mut by_ns: BTreeMap<Option<&str>, Vec<&StructDef>> = BTreeMap::new();
    for s in structs {
        by_ns.entry(split_name(&s.cpp).0).or_default().push(s);
    }
    for (ns, list) in &by_ns {
        writeln!(o)?;
        let indent = if let Some(ns) = ns {
            writeln!(o, "/// Mirrors of the launch-argument structs of C++ namespace `{ns}`.")?;
            writeln!(o, "pub mod {ns} {{")?;
            writeln!(o, "    use super::*;")?;
            "    "
        } else {
            ""
        };
        for s in list {
            emit_struct(o, s, indent)?;
        }
        if ns.is_some() {
            writeln!(o, "}}")?;
        }
    }
    writeln!(o)?;
    writeln!(
        o,
        "// Layout assertions: size, alignment and every field offset equal the C++ compiler's (layout.json)."
    )?;
    writeln!(o, "const _: () = {{")?;
    for s in structs {
        let t = &s.cpp;
        writeln!(o, "    assert!(std::mem::size_of::<{t}>() == {});", s.size)?;
        writeln!(o, "    assert!(std::mem::align_of::<{t}>() == {});", s.align)?;
        for f in &s.fields {
            writeln!(
                o,
                "    assert!(std::mem::offset_of!({t}, {}) == {});",
                ident(&f.name),
                f.offset
            )?;
        }
    }
    writeln!(o, "}};")?;
    writeln!(o)?;
    writeln!(
        o,
        "/// Rust layout of every struct mirror, as rustc computed it (compared with layout.json by a test)."
    )?;
    writeln!(o, "#[cfg(test)]")?;
    writeln!(o, "pub(crate) const RUST_LAYOUTS: &[crate::RustLayout] = &[")?;
    for s in structs {
        let t = &s.cpp;
        writeln!(o, "    crate::RustLayout {{")?;
        writeln!(o, "        name: \"{t}\",")?;
        writeln!(o, "        size: std::mem::size_of::<{t}>(),")?;
        writeln!(o, "        align: std::mem::align_of::<{t}>(),")?;
        writeln!(o, "        fields: &[")?;
        for f in &s.fields {
            let n = ident(&f.name);
            let size = format!("std::mem::size_of::<{}>()", f.ty.field_rust()?);
            writeln!(
                o,
                "            (\"{}\", std::mem::offset_of!({t}, {n}), {size}),",
                f.name
            )?;
        }
        writeln!(o, "        ],")?;
        writeln!(o, "    }},")?;
    }
    writeln!(o, "];")?;
    Ok(())
}

fn emit_struct(o: &mut String, s: &StructDef, ind: &str) -> Result<()> {
    let name = split_name(&s.cpp).1;
    writeln!(
        o,
        "{ind}/// `{}`: {} bytes, align {} (C++ definition: engine/kernels/pack/structs.def).",
        s.cpp, s.size, s.align
    )?;
    writeln!(o, "{ind}#[repr(C)]")?;
    writeln!(o, "{ind}#[derive(Debug, Clone, Copy)]")?;
    writeln!(o, "{ind}pub struct {name} {{")?;
    let mut end = 0;
    let mut pads = 0;
    let mut pad = |o: &mut String, from: usize, to: usize| -> Result<()> {
        if to > from {
            writeln!(
                o,
                "{ind}    /// Padding the C++ compiler inserts (explicit, so the mirror has no padding bytes)."
            )?;
            writeln!(o, "{ind}    pub _pad{pads}: [u8; {}],", to - from)?;
            pads += 1;
        }
        Ok(())
    };
    for f in &s.fields {
        ensure!(f.offset >= end, "{}.{} overlaps", s.cpp, f.name);
        pad(o, end, f.offset)?;
        writeln!(o, "{ind}    /// `{}`, offset {}.", f.cpp, f.offset)?;
        writeln!(o, "{ind}    pub {}: {},", ident(&f.name), f.ty.field_rust()?)?;
        end = f.offset + f.size;
    }
    pad(o, end, s.size)?;
    writeln!(o, "{ind}}}")?;
    writeln!(
        o,
        "{ind}// SAFETY: repr(C) with explicit padding fields, so no padding bytes (checked by the layout assertions:"
    )?;
    writeln!(
        o,
        "{ind}// fields tile the size); every field is Zeroable (integers, floats, DevPtr, arrays, other mirrors)."
    )?;
    writeln!(o, "{ind}unsafe impl bytemuck::Zeroable for {name} {{}}")?;
    writeln!(
        o,
        "{ind}// SAFETY: as above; every field is Pod, so every bit pattern is valid; Copy and 'static."
    )?;
    writeln!(o, "{ind}unsafe impl bytemuck::Pod for {name} {{}}")?;
    Ok(())
}

/// The Rust type of a launcher parameter of C++ type `t` (`'a` is the launcher's lifetime).
fn param_rust(key: &str, i: usize, t: &CType) -> Result<String> {
    Ok(match t {
        CType::Prim(_) => t.field_rust()?,
        CType::Struct(n) => n.clone(),
        CType::Ptr(e) => format!("Ptr<'a, {}>", e.pointee_rust()?),
        _ => bail!("{key}: parameter {i} of kind {t:?}"),
    })
}

/// The statement that appends parameter `v` of C++ type `t` to `args`.
fn push_stmt(t: &CType, v: &str) -> String {
    match t {
        CType::Ptr(_) => format!("        push_ptr(&mut args, {v});\n"),
        _ => format!("        args.value(&{v});\n"),
    }
}

/// One launcher per kernel. A kernel with two or more parameters takes a generated `<Key>Args` struct whose fields
/// are the C++ parameters by name, so a call site names every argument (review R3 finding F13); a one-parameter
/// kernel takes its parameter directly, under its C++ name.
fn emit_launchers(o: &mut String, p: &Pack) -> Result<()> {
    for l in &p.launchers {
        ensure!(
            l.names.len() == l.params.len(),
            "{}: {} names for {} parameters",
            l.key,
            l.names.len(),
            l.params.len()
        );
        if l.params.len() < 2 {
            continue;
        }
        let lt = if l.params.iter().any(|t| matches!(t, CType::Ptr(_))) {
            "<'a>"
        } else {
            ""
        };
        writeln!(o)?;
        writeln!(
            o,
            "/// Arguments of [`Kernels::{}`] by C++ parameter name (`{}`).",
            l.key, l.demangled
        )?;
        writeln!(o, "pub struct {}Args{lt} {{", camel(&l.key))?;
        for (i, (t, n)) in l.params.iter().zip(&l.names).enumerate() {
            writeln!(o, "    /// `{}`", l.cpp_params[i])?;
            writeln!(o, "    pub {}: {},", ident(n), param_rust(&l.key, i, t)?)?;
        }
        writeln!(o, "}}")?;
    }
    writeln!(o)?;
    writeln!(o, "impl Kernels {{")?;
    for l in &p.launchers {
        let cubin = &p.cubins[l.tu].file;
        let (sig, push) = match l.params.as_slice() {
            [] => (String::new(), String::new()),
            [t] => {
                let n = ident(&l.names[0]);
                let ty = match t {
                    CType::Ptr(e) => format!("impl Into<Ptr<'a, {}>>", e.pointee_rust()?),
                    CType::Struct(s) => format!("&{s}"),
                    _ => param_rust(&l.key, 0, t)?,
                };
                let push = match t {
                    CType::Ptr(_) => push_stmt(t, &format!("{n}.into()")),
                    CType::Struct(_) => format!("        args.value({n});\n"),
                    _ => push_stmt(t, &n),
                };
                (format!(", {n}: {ty}"), push)
            }
            _ => {
                let lt = if l.params.iter().any(|t| matches!(t, CType::Ptr(_))) {
                    "<'_>"
                } else {
                    ""
                };
                let mut push = String::new();
                for (t, n) in l.params.iter().zip(&l.names) {
                    push.push_str(&push_stmt(t, &format!("a.{}", ident(n))));
                }
                (format!(", a: {}Args{lt}", camel(&l.key)), push)
            }
        };
        let coop = if l.coop {
            ", cooperative launch (grid-wide sync)"
        } else {
            ""
        };
        writeln!(o, "    /// `{}` in `{cubin}`{coop}.", l.demangled)?;
        writeln!(o, "    ///")?;
        writeln!(o, "    /// # Safety")?;
        writeln!(o, "    ///")?;
        writeln!(
            o,
            "    /// The kernel's memory contract holds for these arguments and `cfg` (crate docs, \"Safety of the launchers\")."
        )?;
        writeln!(o, "    ///")?;
        writeln!(o, "    /// # Errors")?;
        writeln!(o, "    ///")?;
        writeln!(o, "    /// The driver error of the launch.")?;
        let lt = if l.params.len() == 1 && matches!(l.params[0], CType::Ptr(_)) {
            "<'a>"
        } else {
            ""
        };
        writeln!(
            o,
            "    pub unsafe fn {}{lt}(&self, stream: &Stream, cfg: LaunchCfg{sig}) -> Result<()> {{",
            l.key
        )?;
        writeln!(o, "        let mut args = KernelArgs::new();")?;
        o.push_str(&push);
        let f = format!("self.function(KernelId::{})", camel(&l.key));
        writeln!(
            o,
            "        // SAFETY: the arguments match the kernel's parameter list in count, order, size and type (generated"
        )?;
        writeln!(
            o,
            "        // from its C++ signature; offsets and sizes checked against nvcc's KPARAM_INFO by xtask gen-kernels);"
        )?;
        writeln!(o, "        // the kernel's memory contract is the caller's (# Safety).")?;
        let call = if l.coop { "launch_cooperative" } else { "launch" };
        writeln!(o, "        unsafe {{ stream.{call}({f}, cfg, &mut args) }}")?;
        writeln!(o, "    }}")?;
        writeln!(o)?;
    }
    writeln!(o, "}}")?;
    Ok(())
}

